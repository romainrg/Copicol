import AppKit

/// Extraction d'un `CapturedContent` depuis un NSPasteboard, en respectant les conventions
/// nspasteboard.org (contenus confidentiels / éphémères) et la liste d'apps exclues.
public enum PasteboardReader {
    public static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    public static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    public static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    public static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
    public static let maxImageBytes = 100 * 1024 * 1024

    public enum IgnoreReason: Equatable, Sendable {
        case empty
        case concealed
        case transient
        case excludedApp(String)
        case ownWrite
        case unsupported
        case tooLarge
    }

    public enum Outcome: Equatable, Sendable {
        case captured(CapturedContent)
        case ignored(IgnoreReason)
    }

    /// - Parameters:
    ///   - frontmostApp: application active au moment du changement (source par défaut).
    ///   - ownBundleID: identifiant de Copicol, pour ignorer ses propres écritures.
    @MainActor
    public static func read(
        _ pasteboard: NSPasteboard,
        frontmostApp: SourceApp?,
        excludedBundleIDs: Set<String>,
        ownBundleID: String?
    ) -> Outcome {
        guard let types = pasteboard.types, !types.isEmpty else { return .ignored(.empty) }
        if types.contains(concealedType) { return .ignored(.concealed) }
        if types.contains(transientType) || types.contains(autoGeneratedType) { return .ignored(.transient) }

        let declaredSource = types.contains(sourceType) ? pasteboard.string(forType: sourceType) : nil
        if let declaredSource, let ownBundleID, declaredSource == ownBundleID {
            return .ignored(.ownWrite)
        }
        let source = resolveSource(declaredBundleID: declaredSource, frontmostApp: frontmostApp)
        if let bundleID = source?.bundleID, excludedBundleIDs.contains(bundleID) {
            return .ignored(.excludedApp(bundleID))
        }

        guard var content = extractContent(pasteboard, types: types) else { return .ignored(.unsupported) }
        if let data = content.imageData, data.count > maxImageBytes { return .ignored(.tooLarge) }
        content.source = source
        return .captured(content)
    }

    @MainActor
    static func extractContent(_ pasteboard: NSPasteboard, types: [NSPasteboard.PasteboardType]) -> CapturedContent? {
        // 1. Fichiers (Finder) : prioritaires sur l'icône et le nom que Finder ajoute aussi.
        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return CapturedContent(kind: .file, fileURLs: urls)
        }

        let string = pasteboard.string(forType: .string)
        let hasMeaningfulText = !(string ?? "").isEmpty && ContentClassifier.linkURL(from: string ?? "") == nil

        // 2. Images, sauf si un vrai texte les accompagne (cellules de tableur, sélection riche) :
        //    dans ce cas l'image n'est qu'un rendu secondaire du texte.
        if !hasMeaningfulText {
            if let png = pasteboard.data(forType: .png) {
                return CapturedContent(kind: .image, imageData: png, imageIsPNG: true)
            }
            if let tiff = pasteboard.data(forType: .tiff) {
                return CapturedContent(kind: .image, imageData: tiff, imageIsPNG: false)
            }
        }

        // 3. Couleur copiée depuis un sélecteur de couleurs.
        if string == nil, types.contains(.color), let color = NSColor(from: pasteboard),
           let hex = HexColor.hex(from: color) {
            return CapturedContent(kind: .color, text: hex, colorHex: hex)
        }

        // 4. Texte, enrichi ou non.
        let rtf = pasteboard.data(forType: .rtf) ?? pasteboard.data(forType: .rtfd).flatMap(rtf(fromRTFD:))
        let html = pasteboard.data(forType: .html)
        var text = string
        if (text ?? "").isEmpty {
            text = rtf.flatMap { NSAttributedString(rtf: $0, documentAttributes: nil)?.string }
                ?? html.flatMap { NSAttributedString(html: $0, documentAttributes: nil)?.string }
        }
        if let text, !text.isEmpty {
            var content = CapturedContent.text(text)
            if content.kind == .text, rtf != nil || html != nil {
                content.kind = .richText
                content.rtfData = rtf
                content.htmlData = html
            }
            return content
        }

        // 5. URL sans représentation texte.
        if let urlString = pasteboard.string(forType: .URL), let url = URL(string: urlString) {
            return CapturedContent(kind: .link, text: urlString, linkURL: url)
        }
        return nil
    }

    private static func rtf(fromRTFD data: Data) -> Data? {
        guard let attributed = NSAttributedString(rtfd: data, documentAttributes: nil) else { return nil }
        return attributed.rtf(from: NSRange(location: 0, length: attributed.length), documentAttributes: [:])
    }

    private static func resolveSource(declaredBundleID: String?, frontmostApp: SourceApp?) -> SourceApp? {
        guard let declaredBundleID, !declaredBundleID.isEmpty else { return frontmostApp }
        if frontmostApp?.bundleID == declaredBundleID { return frontmostApp }
        return SourceApp(bundleID: declaredBundleID, name: applicationName(for: declaredBundleID))
    }

    public static func applicationName(for bundleID: String) -> String? {
        if let running = NSRunningApplication.runningApplications(withBundleIdentifier: bundleID).first?.localizedName {
            return running
        }
        guard let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID) else { return nil }
        let name = FileManager.default.displayName(atPath: url.path)
        return name.hasSuffix(".app") ? String(name.dropLast(4)) : name
    }
}
